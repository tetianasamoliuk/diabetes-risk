"""Головна сторінка: тема, мета, схема кроків, інструкція."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import streamlit as st

from _common import disclaimer, page_header, setup_page
from risk.config import TOPIC

setup_page("Головна", "🩺")
page_header(
    TOPIC,
    "Це дослідницький застосунок до магістерської роботи. Тему звужено до цукрового діабету "
    "2 типу (ЦД2). Ми беремо реальні дані великого медичного опитування США, перевіряємо, які "
    "ознаки людини пов'язані з діабетом, і будуємо моделі, що оцінюють ризик. "
    "Кожен графік і кожна таблиця мають пояснення простою мовою.",
)

st.header("Мета")
st.write(
    "Показати, які чинники (вік, вага, тиск, холестерин, спадковість тощо) пов'язані з "
    "цукровим діабетом 2 типу, порівняти статистичні моделі з відомою шкалою FINDRISC і "
    "зіставити результати з оцінками IDF та даними МОЗ України."
)

st.header("Кроки дослідження")
steps = [
    "Дані NHANES",
    "Аналітична вибірка",
    "Статистика і фактори",
    "Моделі і FINDRISC",
    "Порівняння з Україною",
    "Оцінка ризику / Експорт",
]
# Блоки кроків зі стрілками між ними
cols = st.columns([4, 1] * (len(steps) - 1) + [4])
for i, name in enumerate(steps):
    cols[2 * i].info(f"**{i + 1}.** {name}")
    if i < len(steps) - 1:
        cols[2 * i + 1].markdown("<h3 style='text-align:center'>→</h3>", unsafe_allow_html=True)

st.header("Як користуватися: 5 кроків")
st.markdown(
    """
1. Відкрийте сторінку **Дані і вибірка**: дізнайтеся, звідки дані і хто потрапив у вибірку.
2. Перейдіть до **Статистика**: подивіться, чим відрізняються люди з діабетом і без.
3. Відкрийте **Фактори ризику**: які ознаки статистично пов'язані з діабетом.
4. Подивіться **Моделі**, **FINDRISC** та **Порівняння з Україною**.
5. У розділі **Оцінка ризику** введіть дані людини, а в **Експорт** завантажте таблиці
   й графіки для тексту роботи.
"""
)

st.header("Що є на кожній сторінці")
st.write(
    "Сторінки відкриваються в меню зліва. На кожній є короткий блок «Що тут відбувається», "
    "результати, а під кожним графіком і таблицею: «Як це читати» та «Що це означає». "
    "Графіки можна завантажити як PNG (300 dpi) для вставки в текст роботи."
)

disclaimer()
